//Secuencias de escape

// 1. \n para realizar saltos de linea
console.log("Primera línea\nSegunda línea\nTercera línea");


// 2. \t para tabulación
console.log("Nombre:\tRosely");
console.log("Curso:\tDAW");


// 3. \" para comillas dobles
console.log("Asignaturas: \"Desarrollo web entorno cliente\"");


// 4. \' para comillas simples
console.log('Asignaturas: \'Desarrollo web entorno cliente\'');


// 5. \\ para colocar barras invertidas
console.log("Ruta: C:\\Users\\Rosely\\Documentos\\DAW");

